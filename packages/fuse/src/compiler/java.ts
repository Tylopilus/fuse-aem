import fs from 'node:fs';
import { FieldJson } from './expr.js';
import { SchemaJson } from './template.js';
import { camel, pascal } from './util.js';
import { ClientType } from './expr.js';

export function generateJavaProps(pkg: string, componentName: string, schema: SchemaJson): string {
  const className = `${pascal(componentName)}Props`;
  const imports = new Set<string>([
    'org.apache.sling.api.SlingHttpServletRequest',
    'org.apache.sling.api.resource.Resource',
    'org.apache.sling.models.annotations.DefaultInjectionStrategy',
    'org.apache.sling.models.annotations.Model',
    'org.apache.sling.models.annotations.injectorspecific.ValueMapValue',
    'dev.fuse.aem.runtime.FuseModel',
  ]);

  const fields = schema.fields;
  const fieldDecls: string[] = [];
  const nestedClasses: string[] = [];

  for (const [name, f] of Object.entries(fields) as [string, FieldJson][]) {
    const javaProp = camel(name);
    const getterName = (f.kind === 'checkbox' ? 'is' : 'get') + pascal(name);

    if (f.kind === 'multifield') {
      imports.add('org.apache.sling.models.annotations.injectorspecific.ChildResource');
      imports.add('java.util.List');
      imports.add('java.util.Collections');
      const itemClassName = pascal(name) + 'Item';

      // Build nested item class
      const subDecls: string[] = [];
      const subFields: Record<string, FieldJson> = f.fields ?? {};
      for (const [subName, subField] of Object.entries(subFields) as [string, FieldJson][]) {
        const subJavaProp = camel(subName);
        const subGetter = (subField.kind === 'checkbox' ? 'is' : 'get') + pascal(subName);
        const subType = javaType(subField);
        subDecls.push(`        @ValueMapValue
        private ${subType} ${subJavaProp};

        public ${subType} ${subGetter}() {
            return ${subJavaProp};
        }`);
      }

      nestedClasses.push(`    @Model(adaptables = Resource.class, defaultInjectionStrategy = DefaultInjectionStrategy.OPTIONAL)
    public static class ${itemClassName} {
${subDecls.join('\n\n')}
    }`);

      fieldDecls.push(`    @ChildResource
    private List<${itemClassName}> ${javaProp};

    public List<${itemClassName}> ${getterName}() {
        return ${javaProp} != null ? ${javaProp} : Collections.emptyList();
    }`);
    } else {
      const type = javaType(f);
      fieldDecls.push(`    @ValueMapValue
    private ${type} ${javaProp};

    public ${type} ${getterName}() {
        return ${javaProp};
    }`);
    }
  }

  const sortedImports = [...imports].sort().map((i) => `import ${i};`).join('\n');

  return `package ${pkg};

${sortedImports}

/**
 * Generated by Fuse from ${componentName} schema – do not edit directly.
 */
@Model(
    adaptables = {SlingHttpServletRequest.class, Resource.class},
    defaultInjectionStrategy = DefaultInjectionStrategy.OPTIONAL
)
public class ${className} extends FuseModel {

${fieldDecls.join('\n\n')}
${nestedClasses.length ? '\n' + nestedClasses.join('\n\n') + '\n' : ''}
}
`;
}

function javaType(field: FieldJson): string {
  switch (field.kind) {
    case 'number':
      return 'Double';
    case 'checkbox':
      return 'boolean';
    case 'text':
    case 'textarea':
    case 'richtext':
    case 'path':
    case 'link':
    case 'image':
    case 'select':
    default:
      return 'String';
  }
}

export interface ParsedJavaModel {
  className: string;
  methods: Array<{ name: string; propName: string; returnType: string; isFuture: boolean }>;
  modelTypes: Record<string, ClientType>;
}

/**
 * Parses a co-located Java model class to discover getters, futures, and property types.
 */
export function parseJavaModel(filePath: string): ParsedJavaModel {
  const code = fs.readFileSync(filePath, 'utf8');
  const classMatch = /public\s+class\s+([A-Za-z0-9_]+)/.exec(code);
  const className = classMatch ? classMatch[1] : 'CustomModel';

  // Find all public getter methods: public <Type> getFoo() or public boolean isFoo()
  const methodRegex = /public\s+([A-Za-z0-9_<>]+(?:\s*<[^>]+>)?)\s+(get|is)([A-Z][A-Za-z0-9_]*)\s*\(\s*\)/g;
  const methods: ParsedJavaModel['methods'] = [];
  const modelTypes: Record<string, ClientType> = {};

  let match;
  while ((match = methodRegex.exec(code)) !== null) {
    const returnType = match[1].trim();
    const prefix = match[2];
    const rawProp = match[3];
    const propName = camel(rawProp);
    const methodName = prefix + rawProp;
    const isFuture = returnType.startsWith('CompletableFuture') || returnType.startsWith('Future');

    methods.push({
      name: methodName,
      propName,
      returnType,
      isFuture,
    });

    if (returnType === 'boolean' || returnType === 'Boolean') {
      modelTypes[propName] = 'boolean';
    } else if (/^(int|Integer|long|Long|double|Double|float|Float)$/.test(returnType)) {
      modelTypes[propName] = 'number';
    } else if (returnType === 'String') {
      modelTypes[propName] = 'string';
    } else {
      modelTypes[propName] = 'json';
    }
  }

  return { className, methods, modelTypes };
}

/**
 * Generates a TypeScript `.d.ts` file representing the Java model methods.
 */
export function generateModelDts(parsed: ParsedJavaModel): string {
  const props = parsed.methods.map((m) => {
    let tsType = 'any';
    if (m.isFuture) {
      // Extract generic type from CompletableFuture<T>
      const inner = m.returnType.match(/<(.+)>/);
      tsType = inner ? `Promise<${mapJavaTypeToTs(inner[1])}>` : 'Promise<any>';
    } else {
      tsType = mapJavaTypeToTs(m.returnType);
    }
    return `  readonly ${m.propName}: ${tsType};`;
  });

  return `// Generated by Fuse from ${parsed.className}.java – do not edit directly.
export interface ${parsed.className} {
${props.join('\n')}
}
`;
}

function mapJavaTypeToTs(javaType: string): string {
  const t = javaType.trim();
  if (t === 'String') return 'string';
  if (t === 'boolean' || t === 'Boolean') return 'boolean';
  if (/^(int|Integer|long|Long|double|Double|float|Float)$/.test(t)) return 'number';
  if (t.startsWith('List<') || t.startsWith('Set<') || t.startsWith('Collection<')) {
    const inner = t.match(/<(.+)>/);
    return inner ? `${mapJavaTypeToTs(inner[1])}[]` : 'any[]';
  }
  if (t.startsWith('Map<')) return 'Record<string, any>';
  return 'any';
}
