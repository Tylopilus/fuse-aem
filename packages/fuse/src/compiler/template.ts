function tagOf(n: ts.JsxElement | ts.JsxSelfClosingElement): ts.JsxTagNameExpression {
  return ts.isJsxElement(n) ? n.openingElement.tagName : n.tagName;
}

function isJsxish(e: ts.Expression): boolean {
  return ts.isJsxElement(e) || ts.isJsxSelfClosingElement(e) || ts.isJsxFragment(e);
}

export function fieldClientType(f: FieldJson | undefined): ClientType {
  if (!f) return 'string';
  if (f.kind === 'checkbox') return 'boolean';
  if (f.kind === 'number') return 'number';
  return 'string';
}
