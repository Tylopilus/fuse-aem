/* ------------------------------------------------------------------------------------------------
 * Public types
 * --------------------------------------------------------------------------------------------- */

export interface SchemaJson {
  title: string;
  group?: string;
  description?: string;
  fields: Record<string, FieldJson>;
}

export interface ComponentEntry {
  /** kebab-case component name (= folder name) */
  name: string;
  pascal: string;
  dir: string;
  file: string;
  isPartial: boolean;
  schema: SchemaJson | null;
  resourceType: string;
  /** FQCN of the class used by HTL (`<Name>Model` if present, otherwise `<Name>Props`) */
  modelClass: string;
  propsClass: string;
  javaPackage: string;
  javaModelFile: string | null;
  /** primitive getter types of the Java model (for client capture) */
  modelTypes: Record<string, ClientType>;
  mockFile: string | null;
  /** JCR path of the partial template script */
  partialPath: string;
}

export interface CompileContext {
  registry: Map<string, ComponentEntry>;
  containerResourceType: string;
  awaitClass: string;
  contextClass: string;
}

export interface ClientSymbol {
  id: string;
  code: string;
}

export interface CompiledTemplate {
  /** HTL source; contains `__FUSE_CHUNK_URL__` when the component has client code */
  htl: string;
  css: string[];
  /** generated chunk entry source (undefined for server-only components) */
  clientEntry?: string;
  hasClient: boolean;
  partialParams?: string[];
  stats: { signals: number; handlers: number; bindings: number; awaits: number; visibleTasks: number };
}

export const CHUNK_PLACEHOLDER = '__FUSE_CHUNK_URL__';
const HOST_PLACEHOLDER = '\u0000FUSE_HOST\u0000';
const FUSE_MODULE = '@fuse-aem/fuse';

/* ------------------------------------------------------------------------------------------------
 * Compiler
 * --------------------------------------------------------------------------------------------- */

interface ClientCapture {
  attrs: Map<string, string>;
}

interface ElementExtras {
  host?: boolean;
  /** forced `hidden` binding from a signal-driven conditional */
  hidden?: { htl: string; client: string; node: ts.Node };
}

interface PropCapture {
  name: string;
  key: string;
  type: ClientType;
  htl: string;
}

export function compileTemplate(entry: ComponentEntry, ctx: CompileContext, source?: string): CompiledTemplate {
  const text = source ?? fs.readFileSync(entry.file, 'utf8');
  const sf = ts.createSourceFile(entry.file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  return new TemplateCompiler(entry, ctx, sf).compile();
}

class TemplateCompiler {
  private uid = 0;
  private symbols: ClientSymbol[] = [];
  private counters = { s: 0, b: 0, v: 0 };
  private signals = new Map<string, SignalInfo>();
  private hostProps = new Map<string, PropCapture>();
  private visible: string[] = [];
  private styles: string[] = [];
  private streamSections: string[] = [];
  private awaitCount = 0;
  private loopDepth = 0;
  private imports = new Map<string, { module: string; imported: string }>();
  private namedHandlers = new Map<string, ts.Expression>();
  private moduleConsts = new Map<string, ts.Expression>();
  private propsAlias: string | null = null;
  private modelAlias: string | null = null;
  private partialParams: Set<string> | null = null;
  private componentStatements = new Set<ts.Statement>();

  constructor(
    private entry: ComponentEntry,
    private ctx: CompileContext,
    private sf: ts.SourceFile,
  ) {}

  compile(): CompiledTemplate {
    this.collectModuleInfo();
    const fn = this.findComponentFunction();
    const scope = this.buildScope(fn);
    const root = this.processBody(fn, scope);

    let main = this.renderTop(root, scope);
    const hasClient = this.symbols.length > 0 || this.signals.size > 0;
    if (hasClient) {
      if (!main.includes(HOST_PLACEHOLDER)) {
        throw FuseCompileError.at(
          root,
          'Components with signals or $-handlers must return a single root HTML element (it becomes the resumable host).',
        );
      }
      main = main.replace(HOST_PLACEHOLDER, this.hostAttributes());
    } else {
      main = main.replace(HOST_PLACEHOLDER, '');
    }

    const header = `<!--/* Generated by Fuse from ${path.basename(this.entry.file)} – do not edit. */-->\n`;
    let htl: string;
    if (this.entry.isPartial) {
      const params = [...(this.partialParams ?? [])];
      htl = `${header}<template data-sly-template.render="\${@ ${params.join(', ')}}">${main}</template>\n`;
      return this.result(htl, hasClient, params);
    }

    const uses = [];
    if (this.awaitCount > 0) uses.push(`data-sly-use.fz="${this.ctx.contextClass}"`);
    uses.push(`data-sly-use.m="${this.entry.modelClass}"`);
    let out = `${header}<sly ${uses.join(' ')}></sly>\n`;
    for (const s of this.signals.values()) {
      if (s.htl && s.initHtl) out += `<sly data-sly-set.${s.htl}="\${${s.initHtl}}"></sly>\n`;
    }

    const required = Object.entries(this.entry.schema?.fields ?? {})
      .filter(([, f]) => f.required)
      .map(([k]) => `m.${k}`);
    let body = main;
    if (required.length) {
      body =
        `<sly data-sly-test.fzcontent="\${${required.join(' && ')}}">${main}</sly>\n` +
        `<sly data-sly-use.fztpl="core/wcm/components/commons/v1/templates.html" ` +
        `data-sly-call="\${fztpl.placeholder @ isEmpty=!fzcontent, classAppend='cmp-${this.entry.name}'}"></sly>`;
    }
    if (this.awaitCount > 0) {
      out += `<sly data-sly-test="\${!fz.streamKey}">${body}</sly>\n`;
      out += this.streamSections.join('\n') + '\n';
    } else {
      out += body + '\n';
    }
    return this.result(out, hasClient);
  }

  private result(htl: string, hasClient: boolean, partialParams?: string[]): CompiledTemplate {
    return {
      htl,
      css: this.styles,
      hasClient,
      clientEntry: hasClient ? this.clientEntry() : undefined,
      partialParams,
      stats: {
        signals: this.signals.size,
        handlers: this.symbols.filter((s) => s.id.startsWith('s')).length,
        bindings: this.symbols.filter((s) => s.id.startsWith('b')).length,
        awaits: this.awaitCount,
        visibleTasks: this.visible.length,
      },
    };
  }

  /* ---------------------------------------------------------------------------------------------
   * Module / component discovery
   * ------------------------------------------------------------------------------------------ */

  private collectModuleInfo(): void {
    for (const st of this.sf.statements) {
      if (ts.isImportDeclaration(st) && ts.isStringLiteral(st.moduleSpecifier)) {
        const mod = st.moduleSpecifier.text;
        const clause = st.importClause;
        if (!clause) continue;
        if (clause.name) this.imports.set(clause.name.text, { module: mod, imported: 'default' });
        if (clause.namedBindings && ts.isNamedImports(clause.namedBindings)) {
          for (const el of clause.namedBindings.elements) {
            this.imports.set(el.name.text, { module: mod, imported: (el.propertyName ?? el.name).text });
          }
        }
      }
      if (ts.isVariableStatement(st)) {
        for (const d of st.declarationList.declarations) {
          if (ts.isIdentifier(d.name) && d.initializer) this.moduleConsts.set(d.name.text, d.initializer);
        }
      }
    }
  }

  private isFuseImport(name: string, imported: string): boolean {
    const i = this.imports.get(name);
    return !!i && i.module === FUSE_MODULE && i.imported === imported;
  }

  private isComponentCall(e: ts.Expression | undefined): e is ts.CallExpression {
    if (!e) return false;
    const n = unwrap(e);
    return ts.isCallExpression(n) && ts.isIdentifier(n.expression) && this.isFuseImport(n.expression.text, 'component$');
  }

  private findComponentFunction(): ts.ArrowFunction | ts.FunctionExpression {
    let call: ts.CallExpression | undefined;
    for (const st of this.sf.statements) {
      if (ts.isExportAssignment(st) && !st.isExportEquals) {
        this.componentStatements.add(st);
        const e = unwrap(st.expression);
        if (this.isComponentCall(e)) call = e as ts.CallExpression;
        else if (ts.isIdentifier(e)) {
          const init = this.moduleConsts.get(e.text);
          if (this.isComponentCall(init)) call = unwrap(init!) as ts.CallExpression;
          for (const s2 of this.sf.statements) {
            if (ts.isVariableStatement(s2) && s2.declarationList.declarations.some((d) => d.initializer === init)) {
              this.componentStatements.add(s2);
            }
          }
        }
      }
      if (ts.isVariableStatement(st)) {
        for (const d of st.declarationList.declarations) {
          if (ts.isIdentifier(d.name) && d.name.text === 'schema') this.componentStatements.add(st);
        }
      }
    }
    if (!call) {
      throw new FuseCompileError(
        `${this.entry.file}: expected \`export default component$(...)\` (imported from '${FUSE_MODULE}').`,
      );
    }
    const fn = call.arguments[0] && unwrap(call.arguments[0]);
    if (!fn || !(ts.isArrowFunction(fn) || ts.isFunctionExpression(fn))) {
      throw FuseCompileError.at(call, 'component$() expects an arrow function.');
    }
    return fn;
  }

  private buildScope(fn: ts.ArrowFunction | ts.FunctionExpression): Scope {
    const scope = new Scope();
    const p = fn.parameters[0];
    if (p) {
      if (!ts.isObjectBindingPattern(p.name)) {
        throw FuseCompileError.at(p, 'Destructure the component context: ({ props, model }) => …');
      }
      for (const el of p.name.elements) {
        const key = (el.propertyName ?? el.name).getText();
        if (!ts.isIdentifier(el.name)) throw FuseCompileError.at(el, 'Nested destructuring is not supported here.');
        if (key === 'props') this.propsAlias = el.name.text;
        else if (key === 'model') this.modelAlias = el.name.text;
        else throw FuseCompileError.at(el, `Unknown context property "${key}" (expected props or model).`);
      }
    }
    if (this.propsAlias) {
      if (this.entry.isPartial) {
        this.partialParams = new Set();
        scope.set(this.propsAlias, { kind: 'params', used: this.partialParams });
      } else {
        scope.set(this.propsAlias, { kind: 'props', fields: this.entry.schema?.fields ?? null, htl: 'm' });
      }
    }
    if (this.modelAlias) {
      if (this.entry.isPartial) throw FuseCompileError.at(fn, 'Partials (no schema) have no Java model.');
      scope.set(this.modelAlias, { kind: 'model', types: this.entry.modelTypes, htl: 'm' });
    }
    return scope;
  }

  private processBody(fn: ts.ArrowFunction | ts.FunctionExpression, scope: Scope): ts.Expression {
    if (!ts.isBlock(fn.body)) return fn.body;
    let ret: ts.Expression | undefined;
    for (const st of fn.body.statements) {
      if (ts.isReturnStatement(st)) {
        if (!st.expression) throw FuseCompileError.at(st, 'A component must return JSX.');
        ret = st.expression;
        continue;
      }
      if (ret) throw FuseCompileError.at(st, 'Statements after return are not allowed.');
      if (ts.isVariableStatement(st)) {
        for (const d of st.declarationList.declarations) this.processDeclaration(d, scope);
        continue;
      }
      if (ts.isExpressionStatement(st)) {
        const e = unwrap(st.expression);
        if (ts.isCallExpression(e) && ts.isIdentifier(e.expression)) {
          const callee = e.expression.text;
          if (this.isFuseImport(callee, 'useStyles$')) {
            this.styles.push(this.readStyles(e));
            continue;
          }
          if (this.isFuseImport(callee, 'useVisibleTask$')) {
            if (this.entry.isPartial) throw FuseCompileError.at(e, 'Partials cannot contain client code.');
            const task = e.arguments[0];
            if (!task) throw FuseCompileError.at(e, 'useVisibleTask$() expects a function.');
            const { sym } = this.addSymbol('v', task, scope, (pro, code) => `{ ${pro} return (${code})(); }`);
            this.visible.push(sym);
            continue;
          }
        }
      }
      throw FuseCompileError.at(
        st,
        'Only hook calls (useSignal, useStyles$, useVisibleTask$, $) and a return statement are allowed in a component body. The body is compiled to HTL and never executed – move logic into the Java model or into $-handlers.',
      );
    }
    if (!ret) throw FuseCompileError.at(fn, 'A component must return JSX.');
    return ret;
  }

  private processDeclaration(d: ts.VariableDeclaration, scope: Scope): void {
    const init = d.initializer && unwrap(d.initializer);
    if (!ts.isIdentifier(d.name) || !init || !ts.isCallExpression(init) || !ts.isIdentifier(init.expression)) {
      throw FuseCompileError.at(d, 'Only `const x = useSignal(…)` and `const fn = $(…)` declarations are allowed.');
    }
    const name = d.name.text;
    const callee = init.expression.text;
    if (this.isFuseImport(callee, 'useSignal')) {
      if (this.entry.isPartial) throw FuseCompileError.at(d, 'Partials cannot contain signals.');
      const sig = this.createSignal(name, init.arguments[0], scope);
      this.signals.set(name, sig);
      scope.set(name, { kind: 'signal', signal: sig });
      return;
    }
    if (this.isFuseImport(callee, '$')) {
      if (!init.arguments[0]) throw FuseCompileError.at(init, '$() expects a function.');
      this.namedHandlers.set(name, init.arguments[0]);
      return;
    }
    throw FuseCompileError.at(init, `"${callee}()" cannot be used in a component body.`);
  }

  private createSignal(name: string, arg: ts.Expression | undefined, scope: Scope): SignalInfo {
    const htlVar = `s_${name.toLowerCase().replace(/[^a-z0-9]/g, '')}`;
    const base = { name, key: kebab(name) };
    if (!arg) return { ...base, htl: htlVar, initHtl: "''", type: 'string', literal: { value: undefined } };
    const a = unwrap(arg);
    if (ts.isNumericLiteral(a) || (ts.isPrefixUnaryExpression(a) && ts.isNumericLiteral(a.operand))) {
      const v = Number(a.getText());
      return { ...base, htl: htlVar, initHtl: String(v), type: 'number', literal: { value: v } };
    }
    if (ts.isStringLiteral(a) || ts.isNoSubstitutionTemplateLiteral(a)) {
      return { ...base, htl: htlVar, initHtl: htlString(a.text), type: 'string', literal: { value: a.text } };
    }
    if (a.kind === ts.SyntaxKind.TrueKeyword || a.kind === ts.SyntaxKind.FalseKeyword) {
      const v = a.kind === ts.SyntaxKind.TrueKeyword;
      return { ...base, htl: htlVar, initHtl: String(v), type: 'boolean', literal: { value: v } };
    }
    if (ts.isArrayLiteralExpression(a) || ts.isObjectLiteralExpression(a) || a.kind === ts.SyntaxKind.NullKeyword) {
      let value: unknown;
      try {
        // eslint-disable-next-line no-new-func
        value = new Function(`return (${ts.transpile(a.getText())})`)();
      } catch {
        throw FuseCompileError.at(a, 'Object/array signal initial values must be JSON-serialisable literals.');
      }
      return { ...base, htl: null, initHtl: null, type: 'json', literal: { value } };
    }
    const e = toHtl(a, scope);
    if (e.reactive) throw FuseCompileError.at(a, 'A signal cannot be initialised from another signal.');
    const type = e.bool ? 'boolean' : this.signalType(a, scope);
    return { ...base, htl: htlVar, initHtl: e.code, type };
  }

  private signalType(node: ts.Expression, scope: Scope): ClientType {
    const n = unwrap(node);
    if (ts.isNumericLiteral(n)) return 'number';
    if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) return 'string';
    if (n.kind === ts.SyntaxKind.TrueKeyword || n.kind === ts.SyntaxKind.FalseKeyword) return 'boolean';
    if (ts.isPrefixUnaryExpression(n)) return n.operator === ts.SyntaxKind.ExclamationToken ? 'boolean' : this.signalType(n.operand, scope);
    if (ts.isPropertyAccessExpression(n) && ts.isIdentifier(n.expression)) {
      const v = scope.get(n.expression.text);
      if (v?.kind === 'props') return fieldClientType(v.fields?.[n.name.text]);
      if (v?.kind === 'model') return v.types[n.name.text] ?? 'string';
    }
    const common = (a: ts.Expression, b: ts.Expression): ClientType => {
      const left = this.signalType(a, scope);
      const right = this.signalType(b, scope);
      if (left !== right) throw FuseCompileError.at(n, 'Signal fallback and conditional values must have the same type so they can resume from HTML.');
      return left;
    };
    if (ts.isConditionalExpression(n)) return common(n.whenTrue, n.whenFalse);
    if (ts.isBinaryExpression(n) && (n.operatorToken.kind === ts.SyntaxKind.BarBarToken || n.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandToken)) {
      return common(n.left, n.right);
    }
    return 'string';
  }

  private readStyles(call: ts.CallExpression): string {
    let a = call.arguments[0] && unwrap(call.arguments[0]);
    if (a && ts.isIdentifier(a)) {
      const imp = this.imports.get(a.text);
      if (imp && /\.css$/.test(imp.module)) {
        return fs.readFileSync(path.resolve(path.dirname(this.entry.file), imp.module), 'utf8');
      }
      const c = this.moduleConsts.get(a.text);
      if (c) a = unwrap(c);
    }
    if (a && ts.isTaggedTemplateExpression(a)) a = a.template;
    if (a && (ts.isStringLiteral(a) || ts.isNoSubstitutionTemplateLiteral(a))) return a.text;
    throw FuseCompileError.at(
      call,
      'useStyles$() expects a string literal, a css`…` template without substitutions, or an imported .css file.',
    );
  }

  /* ---------------------------------------------------------------------------------------------
   * Client symbols
   * ------------------------------------------------------------------------------------------ */

  /**
   * Registers a client symbol. `wrap(prologue, userCode)` returns the function body.
   * Returns the symbol id and the capture attributes that must be placed on the element.
   */
  private addSymbol(
    kind: 's' | 'b' | 'v',
    node: ts.Expression,
    scope: Scope,
    wrap: (prologue: string, code: string) => string,
    codeOverride?: string,
  ): { sym: string; capture: ClientCapture } {
    if (this.entry.isPartial) throw FuseCompileError.at(node, 'Partials (components without a schema) cannot contain client code.');
    const refs = collectClientRefs(node, scope);
    const lines: string[] = [];
    const capture: ClientCapture = { attrs: new Map() };

    // signals
    const sigNames = [...this.signals.keys()].filter((n) => refs.signals.has(n));
    if (sigNames.length) lines.push(`const { ${sigNames.join(', ')} } = __s.sig;`);

    // props / model
    for (const [alias, propsUsed] of refs.props) {
      const v = scope.get(alias)!;
      const entries: string[] = [];
      for (const prop of propsUsed) {
        const isModel = v.kind === 'model';
        const name = isModel ? `model.${prop}` : prop;
        if (!this.hostProps.has(name)) {
          let type: ClientType = 'string';
          if (v.kind === 'props') {
            const f = v.fields?.[prop];
            if (v.fields && !f) throw FuseCompileError.at(node, `"${prop}" is not a field of the component schema.`);
            if (f?.kind === 'multifield') throw FuseCompileError.at(node, `Multifield "${prop}" cannot be captured by client code.`);
            type = fieldClientType(f);
          } else if (v.kind === 'model') {
            type = v.types[prop] ?? 'string';
          }
          this.hostProps.set(name, { name, key: kebab(name), type, htl: `m.${prop}` });
        }
        entries.push(`${JSON.stringify(prop)}: __s.props[${JSON.stringify(name)}]`);
      }
      lines.push(`const ${alias} = { ${entries.join(', ')} };`);
    }

    // loop variables (captured per element)
    for (const [name, paths] of refs.loop) {
      const v = scope.get(name)!;
      if (v.kind === 'index') {
        const attr = `data-fuse-l-${kebab(name)}`;
        capture.attrs.set(attr, `\${${htlString('{0}')} @ format=${v.htl}}`);
        lines.push(`const ${name} = Number(__el.getAttribute(${JSON.stringify(attr)}));`);
      } else if (v.kind === 'item') {
        if (paths.has('')) {
          throw FuseCompileError.at(node, `Client code can only capture properties of "${name}" (e.g. ${name}.title), not the whole item.`);
        }
        const props: string[] = [];
        for (const p of paths) {
          const attr = `data-fuse-l-${kebab(name)}-${kebab(p)}`;
          const t = fieldClientType(v.fields?.[p]);
          const get = `__el.getAttribute(${JSON.stringify(attr)})`;
          if (t === 'boolean') {
            capture.attrs.set(attr, `\${${v.htl}.${p} ? 'true' : 'false'}`);
            props.push(`${JSON.stringify(p)}: ${get} === 'true'`);
          } else if (t === 'number') {
            capture.attrs.set(attr, `\${'{0}' @ format=${v.htl}.${p}}`);
            props.push(`${JSON.stringify(p)}: Number(${get})`);
          } else {
            capture.attrs.set(attr, `\${${v.htl}.${p}}`);
            props.push(`${JSON.stringify(p)}: ${get} ?? ''`);
          }
        }
        lines.push(`const ${name} = { ${props.join(', ')} };`);
      }
    }

    const id = `${kind}${this.counters[kind]++}`;
    const params = kind === 's' ? '(__e, __el, __s)' : '(__s, __el)';
    const code = codeOverride ?? node.getText(this.sf);
    this.symbols.push({ id, code: `export const ${id} = ${params} => ${wrap(lines.join(' '), code)};` });
    return { sym: id, capture };
  }

  private addHandler(attrNode: ts.Node, expr: ts.Expression, scope: Scope) {
    let fnNode = unwrap(expr);
    if (ts.isIdentifier(fnNode)) {
      const named = this.namedHandlers.get(fnNode.text);
      if (!named) throw FuseCompileError.at(fnNode, `"${fnNode.text}" is not a $()-handler declared in this component.`);
      fnNode = named;
    } else if (ts.isCallExpression(fnNode) && ts.isIdentifier(fnNode.expression) && this.isFuseImport(fnNode.expression.text, '$')) {
      fnNode = fnNode.arguments[0];
    }
    if (!(ts.isArrowFunction(fnNode) || ts.isFunctionExpression(fnNode))) {
      throw FuseCompileError.at(attrNode, 'Event handlers must be inline arrow functions or $()-declared handlers.');
    }
    return this.addSymbol('s', fnNode, scope, (pro, code) => `{ ${pro} return (${code})(__e, __el); }`);
  }

  private addBinding(node: ts.Expression, scope: Scope, clientCode: string) {
    return this.addSymbol('b', node, scope, (pro, code) => `{ ${pro} return (${code}); }`, clientCode);
  }

  private hostAttributes(): string {
    const attrs: string[] = [` data-fuse-c="${CHUNK_PLACEHOLDER}"`];
    for (const s of this.signals.values()) {
      const name = `data-fuse-s-${s.key}`;
      if (s.type === 'json') attrs.push(` ${name}="${htlAttrValue(JSON.stringify(s.literal?.value ?? null))}"`);
      else if (s.type === 'boolean') attrs.push(` ${name}="\${${s.htl} ? 'true' : 'false'}"`);
      else if (s.type === 'number') attrs.push(` ${name}="\${'{0}' @ format=${s.htl}}"`);
      else attrs.push(` ${name}="\${${s.htl}}"`);
    }
    for (const p of this.hostProps.values()) {
      const name = `data-fuse-p-${p.key}`;
      if (p.type === 'boolean') attrs.push(` ${name}="\${${p.htl} ? 'true' : 'false'}"`);
      else if (p.type === 'number') attrs.push(` ${name}="\${'{0}' @ format=${p.htl}}"`);
      else attrs.push(` ${name}="\${${p.htl}}"`);
    }
    if (this.visible.length) attrs.push(` data-fuse-visible="${this.visible.join(' ')}"`);
    return attrs.join('');
  }

  private clientEntry(): string {
    const keep: string[] = [];
    for (const st of this.sf.statements) {
      if (this.componentStatements.has(st)) continue;
      keep.push(st.getText(this.sf));
    }
    const meta = {
      signals: [...this.signals.values()].map((s) => ({ name: s.name, key: s.key, type: s.type })),
      props: [...this.hostProps.values()].map((p) => ({ name: p.name, key: p.key, type: p.type })),
    };
    return [
      `// Fuse client chunk for ${path.basename(this.entry.file)} (generated)`,
      ...keep,
      `const __cx = (v) => { const out = []; const add = (x) => { if (!x) return; if (typeof x === 'string') out.push(x); else if (Array.isArray(x)) x.forEach(add); else if (typeof x === 'object') for (const k in x) { if (x[k]) out.push(k); } }; add(v); return out.join(' '); };`,
      `export const $meta = ${JSON.stringify(meta)};`,
      ...this.symbols.map((s) => s.code),
      '',
    ].join('\n');
  }

  /* ---------------------------------------------------------------------------------------------
   * JSX rendering
   * ------------------------------------------------------------------------------------------ */

  private renderTop(node: ts.Expression, scope: Scope): string {
    const n = unwrap(node);
    if ((ts.isJsxElement(n) || ts.isJsxSelfClosingElement(n)) && this.isIntrinsic(tagOf(n))) {
      return this.renderElement(n, scope, { host: true });
    }
    return this.renderExpressionChild(n, scope) + HOST_PLACEHOLDER.slice(0, 0);
  }

  private isIntrinsic(tag: ts.JsxTagNameExpression): boolean {
    return ts.isIdentifier(tag) && /^[a-z]/.test(tag.text) ? true : !ts.isIdentifier(tag) && !ts.isPropertyAccessExpression(tag);
  }

  private renderJsx(n: ts.JsxElement | ts.JsxSelfClosingElement | ts.JsxFragment, scope: Scope, extras: ElementExtras = {}): string {
    if (ts.isJsxFragment(n)) return this.renderChildren(n.children, scope).html;
    const tag = tagOf(n);
    if (this.isIntrinsic(tag)) return this.renderElement(n, scope, extras);
    if (!ts.isIdentifier(tag)) throw FuseCompileError.at(tag, 'Unsupported JSX tag.');
    if (extras.hidden) throw FuseCompileError.at(n, 'Signal-driven conditionals must wrap an HTML element (they compile to a `hidden` toggle).');
    const name = tag.text;
    if (this.isFuseImport(name, 'Await')) return this.renderAwait(n, scope);
    if (this.isFuseImport(name, 'Container')) return this.renderContainer(n, scope);
    if (this.isFuseImport(name, 'Include')) return this.renderInclude(n);
    if (this.isFuseImport(name, 'Fragment')) return ts.isJsxElement(n) ? this.renderChildren(n.children, scope).html : '';
    return this.renderPartialCall(n, name, scope);
  }

  private renderElement(n: ts.JsxElement | ts.JsxSelfClosingElement, scope: Scope, extras: ElementExtras): string {
    const tag = tagOf(n).getText(this.sf);
    const attrsNode = ts.isJsxElement(n) ? n.openingElement.attributes : n.attributes;
    const attrs: string[] = [];
    const bindings: string[] = [];
    const captures = new Map<string, string>();
    const events = new Map<string, string[]>();
    let innerHtml: string | null = null;

    const addCapture = (c: ClientCapture) => c.attrs.forEach((v, k) => captures.set(k, v));

    for (const a of attrsNode.properties) {
      if (ts.isJsxSpreadAttribute(a)) throw FuseCompileError.at(a, 'Spread attributes are not supported (HTL needs static attribute names).');
      let name = a.name.getText(this.sf);
      if (name === 'key' || name === 'children') continue;
      if (name === 'className') name = 'class';
      const init = a.initializer;

      // events
      const ev = /^on([A-Z][A-Za-z]*)\$$/.exec(name);
      if (ev) {
        if (!init || !ts.isJsxExpression(init) || !init.expression) throw FuseCompileError.at(a, 'Event handlers need a function value.');
        const { sym, capture } = this.addHandler(a, init.expression, scope);
        addCapture(capture);
        const evName = ev[1].toLowerCase();
        events.set(evName, [...(events.get(evName) ?? []), sym]);
        continue;
      }
      if (/^on[A-Z]/.test(name)) {
        throw FuseCompileError.at(a, `Use "${name}$" – handlers are lazy-loaded symbols (resumability), not inline listeners.`);
      }
      const pd = /^preventdefault:(.+)$/.exec(name);
      if (pd) {
        attrs.push(` data-fuse-pd-${pd[1].toLowerCase()}`);
        continue;
      }

      // inner html
      if (name === 'html' || name === 'dangerouslySetInnerHTML') {
        if (!init || !ts.isJsxExpression(init) || !init.expression) throw FuseCompileError.at(a, `${name} needs an expression.`);
        let e = unwrap(init.expression);
        if (name === 'dangerouslySetInnerHTML') {
          const p = ts.isObjectLiteralExpression(e) && e.properties.find((x) => x.name?.getText(this.sf) === '__html');
          if (!p || !ts.isPropertyAssignment(p)) throw FuseCompileError.at(e, 'Expected { __html: … }.');
          e = p.initializer;
        }
        const r = toHtl(e, scope, { allowFormat: true });
        if (r.reactive) throw FuseCompileError.at(e, 'Inner HTML cannot depend on signals.');
        innerHtml = r.options ? `\${${r.code}, context='html'}` : `\${${r.code} @ context='html'}`;
        continue;
      }

      if (!init) {
        attrs.push(` ${name}`);
        continue;
      }
      if (ts.isStringLiteral(init)) {
        attrs.push(` ${name}="${htlAttrValue(init.text)}"`);
        continue;
      }
      if (!ts.isJsxExpression(init) || !init.expression) throw FuseCompileError.at(a, 'Unsupported attribute value.');
      const expr = unwrap(init.expression);

      if (name === 'class') {
        const c = this.renderClass(expr, scope);
        attrs.push(` class="${c.value}"`);
        if (c.reactive) {
          const { sym, capture } = this.addBinding(expr, scope, `__cx(${expr.getText(this.sf)})`);
          addCapture(capture);
          bindings.push(`attr:class=${sym}`);
        }
        continue;
      }

      if (ts.isStringLiteral(expr) || ts.isNoSubstitutionTemplateLiteral(expr)) {
        attrs.push(` ${name}="${htlAttrValue(expr.text)}"`);
        continue;
      }

      const { value, reactive, clientCode } = this.renderAttrExpr(name, expr, scope);
      if (value !== null) attrs.push(` ${name}="${value}"`);
      if (reactive) {
        const { sym, capture } = this.addBinding(expr, scope, clientCode);
        addCapture(capture);
        bindings.push(`attr:${name}=${sym}`);
      }
    }

    if (extras.hidden) {
      if (attrs.some((x) => x.startsWith(' hidden'))) throw FuseCompileError.at(n, 'Element already has a hidden attribute.');
      attrs.push(` hidden="\${${extras.hidden.htl}}"`);
      const { sym, capture } = this.addBinding(extras.hidden.node as ts.Expression, scope, extras.hidden.client);
      addCapture(capture);
      bindings.push(`attr:hidden=${sym}`);
    }

    let childrenHtml = '';
    if (ts.isJsxElement(n)) {
      if (innerHtml !== null && n.children.some((c) => !(ts.isJsxText(c) && !c.text.trim()))) {
        throw FuseCompileError.at(n, 'An element with html/dangerouslySetInnerHTML cannot have children.');
      }
      const ch = this.renderChildren(n.children, scope, true);
      childrenHtml = ch.html;
      if (ch.textBinding) {
        bindings.push(`text=${ch.textBinding.sym}`);
        ch.textBinding.capture.attrs.forEach((v, k) => captures.set(k, v));
      }
    }
    if (innerHtml !== null) childrenHtml = innerHtml;

    for (const [evName, syms] of events) attrs.push(` data-fuse-on-${evName}="${syms.join(' ')}"`);
    if (bindings.length) attrs.push(` data-fuse-b="${bindings.join(' ')}"`);
    captures.forEach((v, k) => attrs.push(` ${k}="${v}"`));
    if (extras.host) attrs.push(HOST_PLACEHOLDER);

    const open = `<${tag}${attrs.join('')}>`;
    if (VOID_ELEMENTS.has(tag)) {
      if (childrenHtml) throw FuseCompileError.at(n, `<${tag}> cannot have children.`);
      return open;
    }
    return `${open}${childrenHtml}</${tag}>`;
  }

  /** Attribute with a dynamic expression. Returns the HTL value and client binding code. */
  private renderAttrExpr(name: string, expr: ts.Expression, scope: Scope): { value: string | null; reactive: boolean; clientCode: string } {
    const src = expr.getText(this.sf);
    let r: HtlExpr | null = null;
    let err: unknown;
    try {
      r = toHtl(expr, scope, { allowFormat: true });
    } catch (e) {
      err = e;
    }
    const isBoolAttr = BOOLEAN_ATTRIBUTES.has(name.toLowerCase());
    const stringify = /^(aria|data)-/.test(name);
    if (!r) {
      // server value via constant folding (signals with literal initial values)
      const folded = constantFold(expr, scope);
      if (!folded) throw err;
      const v = folded.value;
      const value = v === false || v == null ? (stringify && v === false ? 'false' : null) : v === true ? (stringify ? 'true' : '') : htlAttrValue(String(v));
      return { value, reactive: true, clientCode: stringify ? `String(${src})` : src };
    }
    let code = r.code;
    let clientCode = src;
    if (stringify && r.bool) {
      code = `${r.atom ? code : `(${code})`} ? 'true' : 'false'`;
      clientCode = `String(${src})`;
    } else if (isBoolAttr) {
      clientCode = `!!(${src})`;
    }
    return { value: `\${${code}}`, reactive: r.reactive, clientCode };
  }

  private renderClass(expr: ts.Expression, scope: Scope): { value: string; reactive: boolean } {
    const parts: string[] = [];
    let reactive = false;
    const item = (e: ts.Expression) => {
      const u = unwrap(e);
      if (ts.isStringLiteral(u) || ts.isNoSubstitutionTemplateLiteral(u)) {
        if (u.text.trim()) parts.push(htlAttrValue(u.text.trim()));
        return;
      }
      if (ts.isBinaryExpression(u) && u.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandToken) {
        const c = this.htlOrFold(u.left, scope, { test: true });
        const v = toHtl(u.right, scope);
        reactive ||= c.reactive || v.reactive;
        parts.push(`\${${c.atom ? c.code : `(${c.code})`} ? ${v.atom ? v.code : `(${v.code})`} : ''}`);
        return;
      }
      if (ts.isArrayLiteralExpression(u)) {
        u.elements.forEach((el) => item(el as ts.Expression));
        return;
      }
      if (ts.isObjectLiteralExpression(u)) {
        for (const p of u.properties) {
          if (!ts.isPropertyAssignment(p)) throw FuseCompileError.at(p, 'Only `"class": condition` entries are supported.');
          const cls = ts.isStringLiteral(p.name) || ts.isIdentifier(p.name) ? p.name.text : null;
          if (!cls) throw FuseCompileError.at(p.name, 'Class names must be static.');
          const c = this.htlOrFold(p.initializer, scope, { test: true });
          reactive ||= c.reactive;
          parts.push(`\${${c.atom ? c.code : `(${c.code})`} ? ${htlString(cls)} : ''}`);
        }
        return;
      }
      const r = toHtl(u, scope, { allowFormat: true });
      reactive ||= r.reactive;
      parts.push(`\${${r.code}}`);
    };
    item(expr);
    return { value: parts.join(' '), reactive };
  }

  /** Translate to HTL, falling back to compile-time constant folding of literal-initialised signals. */
  private htlOrFold(e: ts.Expression, scope: Scope, opts: { test?: boolean } = {}): HtlExpr {
    try {
      return toHtl(e, scope, opts);
    } catch (err) {
      const f = constantFold(e, scope);
      if (!f) throw err;
      return { code: f.value ? 'true' : 'false', reactive: true, bool: true, atom: true };
    }
  }

  private renderChildren(
    children: ts.NodeArray<ts.JsxChild>,
    scope: Scope,
    allowParentBinding = false,
  ): { html: string; textBinding?: { sym: string; capture: ClientCapture } } {
    const meaningful = children.filter((c) => !(ts.isJsxText(c) && !cleanJsxText(c.text)));
    // a single reactive text expression → bind on the parent element
    if (allowParentBinding && meaningful.length === 1 && ts.isJsxExpression(meaningful[0]) && meaningful[0].expression) {
      const e = unwrap(meaningful[0].expression);
      if (!isJsxish(e) && this.isReactiveText(e, scope)) {
        const t = this.renderText(e, scope);
        return { html: t.html, textBinding: t.binding };
      }
    }
    let html = '';
    for (const c of children) {
      if (ts.isJsxText(c)) html += htlText(cleanJsxText(c.text));
      else if (ts.isJsxExpression(c)) {
        if (c.expression) html += this.renderExpressionChild(unwrap(c.expression), scope);
      } else html += this.renderJsx(c as any, scope);
    }
    return { html };
  }

  private isReactiveText(e: ts.Expression, scope: Scope): boolean {
    return collectClientRefs(e, scope).signals.size > 0;
  }

  private renderText(e: ts.Expression, scope: Scope): { html: string; binding?: { sym: string; capture: ClientCapture } } {
    let html: string;
    let reactive: boolean;
    try {
      const r = toHtl(e, scope, { allowFormat: true });
      html = `\${${r.code}}`;
      reactive = r.reactive;
    } catch (err) {
      const f = constantFold(e, scope);
      if (!f) throw err;
      html = htlText(String(f.value ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;'));
      reactive = true;
    }
    if (!reactive) return { html };
    const b = this.addBinding(e, scope, e.getText(this.sf));
    return { html, binding: b };
  }

  private renderExpressionChild(e: ts.Expression, scope: Scope): string {
    if (ts.isJsxElement(e) || ts.isJsxSelfClosingElement(e) || ts.isJsxFragment(e)) return this.renderJsx(e, scope);

    // cond && <X/>
    if (ts.isBinaryExpression(e) && e.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandToken) {
      return this.renderConditional(e.left, e.right, null, scope);
    }
    // cond ? <A/> : <B/>
    if (ts.isConditionalExpression(e) && (isJsxish(unwrap(e.whenTrue)) || isJsxish(unwrap(e.whenFalse)))) {
      return this.renderConditional(e.condition, e.whenTrue, e.whenFalse, scope);
    }
    // list.map((item, i) => …)
    if (ts.isCallExpression(e) && ts.isPropertyAccessExpression(e.expression) && e.expression.name.text === 'map') {
      return this.renderLoop(e, scope);
    }
    // text
    const t = this.renderText(e, scope);
    if (t.binding) {
      const caps = [...t.binding.capture.attrs].map(([k, v]) => ` ${k}="${v}"`).join('');
      return `<span data-fuse-b="text=${t.binding.sym}"${caps}>${t.html}</span>`;
    }
    return t.html;
  }

  private renderConditional(cond: ts.Expression, a: ts.Expression, b: ts.Expression | null, scope: Scope): string {
    const reactive = this.isReactiveText(cond, scope);
    if (reactive) {
      const c = this.htlOrFold(cond, scope, { test: true });
      const condSrc = cond.getText(this.sf);
      const branch = (x: ts.Expression | null, negate: boolean) => {
        if (!x) return '';
        const u = unwrap(x);
        if (u.kind === ts.SyntaxKind.NullKeyword || (ts.isIdentifier(u) && u.text === 'undefined')) return '';
        if (!(ts.isJsxElement(u) || ts.isJsxSelfClosingElement(u))) {
          throw FuseCompileError.at(u, 'Signal-driven conditionals must render a single HTML element (compiled to a `hidden` toggle).');
        }
        const ccode = c.atom ? c.code : `(${c.code})`;
        return this.renderJsx(u, scope, {
          hidden: {
            htl: negate ? `!${ccode}` : ccode,
            client: negate ? `!(${condSrc})` : `!!(${condSrc})`,
            node: cond,
          },
        });
      };
      return branch(a, true) + branch(b, false);
    }
    const c = toHtl(cond, scope, { test: true });
    const render = (x: ts.Expression) => {
      const u = unwrap(x);
      if (u.kind === ts.SyntaxKind.NullKeyword || (ts.isIdentifier(u) && u.text === 'undefined')) return '';
      return this.renderExpressionChild(u, scope);
    };
    if (!b) return `<sly data-sly-test="\${${c.code}}">${render(a)}</sly>`;
    const v = `t_${++this.uid}`;
    const whenTrue = render(a);
    const whenFalse = render(b);
    return (
      `<sly data-sly-test.${v}="\${${c.code}}">${whenTrue}</sly>` + (whenFalse ? `<sly data-sly-test="\${!${v}}">${whenFalse}</sly>` : '')
    );
  }

  private renderLoop(call: ts.CallExpression, scope: Scope): string {
    const listExpr = (call.expression as ts.PropertyAccessExpression).expression;
    const list = toHtl(listExpr, scope);
    if (list.reactive) throw FuseCompileError.at(listExpr, 'Signal-driven lists are not supported yet – lists must come from props, model or <Await> values.');
    const cb = call.arguments[0] && unwrap(call.arguments[0]);
    if (!cb || !(ts.isArrowFunction(cb) || ts.isFunctionExpression(cb))) throw FuseCompileError.at(call, '.map() expects an arrow function.');
    const [itemP, indexP] = cb.parameters;
    if (!itemP || !ts.isIdentifier(itemP.name)) throw FuseCompileError.at(cb, '.map() callback needs an item parameter.');
    const itemName = itemP.name.text;
    const v = `${itemName.toLowerCase().replace(/[^a-z0-9]/g, '')}_${++this.uid}`;

    // item field types (multifield)
    let fields: Record<string, FieldJson> | null = null;
    const le = unwrap(listExpr);
    if (ts.isPropertyAccessExpression(le) && ts.isIdentifier(le.expression)) {
      const sv = scope.get(le.expression.text);
      if (sv?.kind === 'props') fields = sv.fields?.[le.name.text]?.fields ?? null;
    }
    const inner = scope.child();
    inner.set(itemName, { kind: 'item', htl: v, fields });
    if (indexP) {
      if (!ts.isIdentifier(indexP.name)) throw FuseCompileError.at(indexP, 'Index parameter must be an identifier.');
      inner.set(indexP.name.text, { kind: 'index', htl: `${v}List.index` });
    }
    let body: ts.Expression;
    if (ts.isBlock(cb.body)) {
      const ret = cb.body.statements.length === 1 && ts.isReturnStatement(cb.body.statements[0]) ? cb.body.statements[0].expression : undefined;
      if (!ret) throw FuseCompileError.at(cb.body, '.map() callbacks may only contain a return statement.');
      body = ret;
    } else body = cb.body;
    this.loopDepth++;
    const html = this.renderExpressionChild(unwrap(body), inner);
    this.loopDepth--;
    return `<sly data-sly-list.${v}="\${${list.code}}">${html}</sly>`;
  }

  /* ---------------------------------------------------------------------------------------------
   * Built-ins
   * ------------------------------------------------------------------------------------------ */

  private jsxAttr(n: ts.JsxElement | ts.JsxSelfClosingElement, name: string): ts.JsxAttribute | undefined {
    const attrs = ts.isJsxElement(n) ? n.openingElement.attributes : n.attributes;
    return attrs.properties.find((a): a is ts.JsxAttribute => ts.isJsxAttribute(a) && a.name.getText(this.sf) === name);
  }

  private staticString(n: ts.JsxElement | ts.JsxSelfClosingElement, name: string, required = true): string | undefined {
    const a = this.jsxAttr(n, name);
    if (!a) {
      if (required) throw FuseCompileError.at(n, `Missing "${name}" attribute.`);
      return undefined;
    }
    const init = a.initializer;
    if (init && ts.isStringLiteral(init)) return init.text;
    if (init && ts.isJsxExpression(init) && init.expression && ts.isStringLiteral(unwrap(init.expression))) {
      return (unwrap(init.expression) as ts.StringLiteral).text;
    }
    throw FuseCompileError.at(a, `"${name}" must be a static string.`);
  }

  private renderAwait(n: ts.JsxElement | ts.JsxSelfClosingElement, scope: Scope): string {
    if (this.loopDepth > 0) throw FuseCompileError.at(n, '<Await> cannot be used inside a loop.');
    if (this.entry.isPartial) throw FuseCompileError.at(n, '<Await> is not supported in partials.');
    const valueAttr = this.jsxAttr(n, 'value');
    if (!valueAttr?.initializer || !ts.isJsxExpression(valueAttr.initializer) || !valueAttr.initializer.expression) {
      throw FuseCompileError.at(n, '<Await> needs a value={model.something} attribute.');
    }
    const value = toHtl(valueAttr.initializer.expression, scope);
    if (value.reactive) throw FuseCompileError.at(valueAttr, '<Await value> cannot depend on signals.');

    const fbAttr = this.jsxAttr(n, 'fallback');
    let fallback = '';
    if (fbAttr?.initializer && ts.isJsxExpression(fbAttr.initializer) && fbAttr.initializer.expression) {
      fallback = this.renderExpressionChild(unwrap(fbAttr.initializer.expression), scope);
    }

    const kids = ts.isJsxElement(n) ? n.children.filter((c) => !(ts.isJsxText(c) && !c.text.trim())) : [];
    const child = kids[0];
    const fn = child && ts.isJsxExpression(child) && child.expression ? unwrap(child.expression) : undefined;
    if (kids.length !== 1 || !fn || !(ts.isArrowFunction(fn) || ts.isFunctionExpression(fn))) {
      throw FuseCompileError.at(n, '<Await> expects a single render function child: {(value) => …}.');
    }
    const p = fn.parameters[0];
    const inner = scope.child();
    const key = `aw${this.awaitCount++}`;
    let setVar = '';
    if (p) {
      if (!ts.isIdentifier(p.name)) throw FuseCompileError.at(p, 'Use a plain parameter name.');
      const v = `${p.name.text.toLowerCase().replace(/[^a-z0-9]/g, '')}_${++this.uid}`;
      inner.set(p.name.text, { kind: 'value', htl: v });
      setVar = v;
    }
    let body: ts.Expression;
    if (ts.isBlock(fn.body)) {
      const ret = fn.body.statements.length === 1 && ts.isReturnStatement(fn.body.statements[0]) ? fn.body.statements[0].expression : undefined;
      if (!ret) throw FuseCompileError.at(fn.body, 'The <Await> render function may only contain a return statement.');
      body = ret;
    } else body = fn.body;
    const resolved = this.renderExpressionChild(unwrap(body), inner);
    const withValue = setVar ? `<sly data-sly-set.${setVar}="\${${key}.value}">${resolved}</sly>` : resolved;

    this.streamSections.push(
      `<sly data-sly-test="\${fz.streamKey == '${key}'}"><sly data-sly-use.${key}="\${'${this.ctx.awaitClass}' @ key='${key}'}">${withValue}</sly></sly>`,
    );
    return (
      `<sly data-sly-use.${key}="\${'${this.ctx.awaitClass}' @ key='${key}', value=${value.code}}">` +
      `<fuse-await data-sly-test="\${${key}.pending}" id="\${${key}.id}">${fallback}</fuse-await>` +
      `<sly data-sly-test="\${!${key}.pending}">${withValue}</sly></sly>`
    );
  }

  private renderContainer(n: ts.JsxElement | ts.JsxSelfClosingElement, scope: Scope): string {
    void scope;
    const name = this.staticString(n, 'name')!;
    const cls = this.staticString(n, 'class', false);
    const rt = this.staticString(n, 'resourceType', false) ?? this.ctx.containerResourceType;
    const res = `data-sly-resource="\${${htlString(name)} @ resourceType=${htlString(rt)}}"`;
    return cls ? `<div class="${htlAttrValue(cls)}" ${res}></div>` : `<sly ${res}></sly>`;
  }

  private renderInclude(n: ts.JsxElement | ts.JsxSelfClosingElement): string {
    const name = this.staticString(n, 'name')!;
    const typeAttr = this.jsxAttr(n, 'type');
    let rt: string | undefined;
    const init = typeAttr?.initializer;
    if (init && ts.isStringLiteral(init)) rt = init.text;
    else if (init && ts.isJsxExpression(init) && init.expression) {
      const e = unwrap(init.expression);
      if (ts.isStringLiteral(e)) rt = e.text;
      else if (ts.isIdentifier(e)) {
        const target = this.resolveImportedComponent(e.text, e);
        if (target.isPartial) throw FuseCompileError.at(e, `"${e.text}" is a partial – render it as <${e.text} … /> instead.`);
        rt = target.resourceType;
      }
    }
    if (!rt) throw FuseCompileError.at(n, '<Include> needs type={ImportedComponent} or a resource type string.');
    return `<sly data-sly-resource="\${${htlString(name)} @ resourceType=${htlString(rt)}}"></sly>`;
  }

  private resolveImportedComponent(local: string, node: ts.Node): ComponentEntry {
    const imp = this.imports.get(local);
    if (!imp || !imp.module.startsWith('.')) {
      throw FuseCompileError.at(node, `<${local}> must be imported from a component file (relative import).`);
    }
    const base = path.resolve(path.dirname(this.entry.file), imp.module);
    const candidates = [base, `${base}.tsx`, `${base}.ts`, path.join(base, `${path.basename(base)}.tsx`), path.join(base, 'index.tsx')];
    for (const c of candidates) {
      const hit = [...this.ctx.registry.values()].find((r) => path.resolve(r.file) === c);
      if (hit) return hit;
    }
    throw FuseCompileError.at(node, `Cannot resolve component "${imp.module}".`);
  }

  private renderPartialCall(n: ts.JsxElement | ts.JsxSelfClosingElement, name: string, scope: Scope): string {
    const target = this.resolveImportedComponent(name, n);
    if (!target.isPartial) {
      throw FuseCompileError.at(n, `<${name}> is an authorable component (it has a schema). Use <Include name="…" type={${name}} /> to embed it.`);
    }
    if (ts.isJsxElement(n) && n.children.some((c) => !(ts.isJsxText(c) && !c.text.trim()))) {
      throw FuseCompileError.at(n, 'Partials cannot receive children (HTL templates have no slots).');
    }
    const attrs = (ts.isJsxElement(n) ? n.openingElement.attributes : n.attributes).properties;
    const args: string[] = [];
    for (const a of attrs) {
      if (!ts.isJsxAttribute(a)) throw FuseCompileError.at(a, 'Spread props are not supported.');
      const pname = a.name.getText(this.sf);
      const init = a.initializer;
      let code: string;
      if (!init) code = 'true';
      else if (ts.isStringLiteral(init)) code = htlString(init.text);
      else if (ts.isJsxExpression(init) && init.expression) {
        const r = toHtl(init.expression, scope);
        if (r.reactive) throw FuseCompileError.at(a, 'Partial props cannot depend on signals.');
        code = r.code;
      } else throw FuseCompileError.at(a, 'Unsupported prop value.');
      args.push(`${pname}=${code}`);
    }
    const v = `pt_${target.name.replace(/[^a-z0-9]/gi, '').toLowerCase()}`;
    return `<sly data-sly-use.${v}="${target.partialPath}" data-sly-call="\${${v}.render${args.length ? ' @ ' + args.join(', ') : ''}}"></sly>`;
  }
}

